#!/usr/bin/env python3
"""Generate the docs of each service from its code.

A member takes part when it has a `config_schema.json`.
For each one the script loads `<package>.config.Config` from the member's
`dev_config.yaml` and writes:

- `config_schema.json`, the JSON Schema of the settings;
- `example_config.yaml`, the loaded settings, with secrets masked;
- the parameter list in the README, between the `config-docs` markers;
- `openapi.yaml`, the OpenAPI specification of its REST API, when it has one.

It also fails when a config field that holds a secret is not typed as a pydantic
`Secret`, since hexkit logs the whole config at startup and masks only those.
With `--check` it writes nothing and fails when a file is out of date.
Given paths, it handles only the members they belong to; a path outside a member,
such as this script, selects them all, and so does giving none.
It ports the retired template's scripts/update_config_docs.py,
scripts/update_openapi_docs.py and the config part of its scripts/update_readme.py,
so the output matches what the single-service repositories generated, apart from
what rumdl reflows.

Usage:
    uv run python scripts/service_docs.py [--check] [path ...]
"""

from __future__ import annotations

import argparse
import difflib
import importlib
import json
import os
import pathlib
import re
import subprocess
import sys
import typing
import warnings
from collections.abc import Iterator

import jsonschema2md
import yaml
from fastapi import FastAPI
from pydantic import BaseModel, Secret, SecretBytes, SecretStr

ROOT = pathlib.Path(__file__).resolve().parents[1]
MEMBER_GLOBS = ("libs/*", "services/*", "tools/*")
SCHEMA_FILE = "config_schema.json"
EXAMPLE_FILE = "example_config.yaml"
DEV_CONFIG_FILE = "dev_config.yaml"
README_FILE = "README.md"
OPENAPI_FILE = "openapi.yaml"
BEGIN_MARKER = (
    "<!-- config-docs: begin (generated by `just service-docs`, do not edit) -->"
)
END_MARKER = "<!-- config-docs: end -->"

# A bare URL, not already inside <...> or a Markdown link target; trailing
# punctuation belongs to the sentence, not to the URL.
BARE_URL = re.compile(r"(?<![<(])\bhttps?://\w[^\s<>)]*?(?=[.,;:]?(?:\s|$))")
INLINE_CODE = re.compile(r"(`+).*?\1")

# Names of string fields that hold a secret; a `_path` only points to one.
SECRET_NAME = re.compile(
    r"password|passphrase|credentials|secret|private_key(?!_path)|signing_key"
    r"|encryption_key|token$|dsn$"
)
# Secrets whose name does not say so, by member.
SECRET_FIELDS = {"auth-service": {"auth_key"}}
# Names that match SECRET_NAME but hold no secret, each with the reason.
NOT_SECRET = {
    "vault_secrets_mount_point": "the path of the Vault secrets engine",
}
SECRET_TYPES = (SecretStr, SecretBytes, Secret)


def members(paths: list[str]) -> list[pathlib.Path]:
    """The member directories that carry a config schema, all or those of the paths."""
    found = sorted(
        path.parent
        for pattern in MEMBER_GLOBS
        for path in ROOT.glob(f"{pattern}/{SCHEMA_FILE}")
    )
    wanted = set()
    for path in paths:
        parts = (ROOT / path).resolve().relative_to(ROOT).parts
        if len(parts) < 2 or parts[0] not in ("libs", "services", "tools"):
            return found
        wanted.add(ROOT / parts[0] / parts[1])
    return [member for member in found if member in wanted] if paths else found


def package_name(member: pathlib.Path) -> str:
    """The member's single import package under src/."""
    packages = [
        path.name
        for path in (member / "src").iterdir()
        if (path / "__init__.py").is_file()
    ]
    if len(packages) != 1:
        sys.exit(f"error: expected one package under {member}/src, found {packages}")
    return packages[0]


def load_config(member: pathlib.Path):
    """Instantiate the member's Config from its dev config.

    The schema comes from the instance rather than from `Config`, because hexkit's
    `config_from_yaml` turns the class into a constructor function.
    """
    package = package_name(member)
    source = member / DEV_CONFIG_FILE
    if not source.is_file():
        sys.exit(f"error: {member} has a {SCHEMA_FILE} but no {DEV_CONFIG_FILE}")
    # Some config modules build a module-level CONFIG on import, which reads the YAML
    # named by this variable, as the member's conftest.py sets it for the tests.
    os.environ.setdefault(f"{package.upper()}_CONFIG_YAML", str(source))
    module = importlib.import_module(f"{package}.config")
    return module.Config(config_yaml=source)


def annotation_types(annotation) -> Iterator[type]:
    """The classes an annotation names, its type arguments and their origins included."""
    if isinstance(annotation, type):
        yield annotation
    origin = typing.get_origin(annotation)
    if isinstance(origin, type):
        yield origin
    for argument in typing.get_args(annotation):
        yield from annotation_types(argument)


def unmasked_secrets(
    model: type[BaseModel], secret_fields: set[str], prefix: str = ""
) -> Iterator[str]:
    """The dotted paths of the model's secret fields not typed as a pydantic Secret.

    A field counts as secret when it is listed in `secret_fields`, or when it is
    typed as a string and its name matches SECRET_NAME; nested models are searched.
    """
    for name, field in model.model_fields.items():
        path = prefix + name
        types = set(annotation_types(field.annotation))
        nested = {t for t in types if issubclass(t, BaseModel)}
        for nested_model in sorted(nested, key=lambda t: t.__name__):
            yield from unmasked_secrets(nested_model, secret_fields, f"{path}.")
        if any(issubclass(t, SECRET_TYPES) for t in types):
            continue
        if path in secret_fields or (
            SECRET_NAME.search(name) and name not in NOT_SECRET and types & {str, bytes}
        ):
            yield path


def render_schema(config) -> str:
    """The JSON Schema of the settings, as the template wrote it."""
    return json.dumps(type(config).model_json_schema(), indent=2) + "\n"


def render_example(config) -> str:
    """The example config YAML, as the template wrote it."""
    settings = config.model_dump(mode="json", by_alias=True)
    return yaml.dump(settings, indent=2, sort_keys=True)


def auth_service_app(config) -> FastAPI:
    """The auth service's REST app, with the routes it serves.

    The service builds its app only while connecting to its database and event
    broker, so this assembles the same app from its routers, as the service's own
    repository did.
    """
    package = importlib.import_module("auth_service")
    prepare = importlib.import_module("auth_service.prepare")
    app = FastAPI(
        title=package.TITLE,
        description=package.DESCRIPTION,
        version=package.VERSION,
        contact=package.CONTACT,
        license_info=package.LICENSE_INFO,
        openapi_tags=package.TAGS_METADATA,
    )
    for router in (
        prepare.base_router,
        prepare.users_router,
        prepare.claims_router,
        prepare.access_router,
    ):
        app.include_router(router)
    return app


# The services that do not build their REST app with
# `<package>.adapters.inbound.fastapi_.configure.get_configured_app(config=...)`.
APP_FACTORIES = {
    "auth-service": auth_service_app,
    "test-oidc-provider": lambda config: importlib.import_module("top.api.main").app,
}


def openapi_app(member: pathlib.Path, config) -> FastAPI:
    """The member's REST app, configured from its dev config."""
    factory = APP_FACTORIES.get(member.name)
    if factory:
        return factory(config)
    configure = importlib.import_module(
        f"{package_name(member)}.adapters.inbound.fastapi_.configure"
    )
    return configure.get_configured_app(config=config)


def render_openapi(app: FastAPI) -> str:
    """The OpenAPI specification in YAML, as the template wrote it."""
    return yaml.safe_dump(app.openapi())


def render_parameters(schema: str) -> str:
    """The Markdown parameter list, with the schema's $defs under a subheading."""
    parser = jsonschema2md.Parser(examples_as_yaml=False, show_examples="all")
    lines = parser.parse_schema(flatten_descriptions(json.loads(schema)))
    lines = lines[lines.index("## Properties\n\n") + 1 :]
    text = "".join(lines).strip()
    text = text.replace("\n## Definitions\n", "\n#### Definitions\n")
    return wrap_bare_urls(text)


def flatten_descriptions(node):
    """The schema with each description on one line.

    jsonschema2md copies a docstring's line breaks into the list item, where they end
    it, and turns a blank line into <br>; rumdl then puts each sentence on its own line.
    """
    if isinstance(node, dict):
        return {
            key: " ".join(value.split())
            if key == "description" and isinstance(value, str)
            else flatten_descriptions(value)
            for key, value in node.items()
        }
    if isinstance(node, list):
        return [flatten_descriptions(item) for item in node]
    return node


def wrap_bare_urls(text: str) -> str:
    """Wrap bare URLs in <...> outside code blocks, as rumdl's MD034 asks."""
    lines, in_code = [], False
    for line in text.splitlines(keepends=True):
        if line.lstrip().startswith("```"):
            in_code = not in_code
        elif not in_code:
            line = wrap_outside_code_spans(line)
        lines.append(line)
    return "".join(lines)


def wrap_outside_code_spans(line: str) -> str:
    """Wrap the bare URLs of one line, leaving `code spans` alone."""
    parts, start = [], 0
    for span in INLINE_CODE.finditer(line):
        parts.append(BARE_URL.sub(r"<\g<0>>", line[start : span.start()]))
        parts.append(span.group(0))
        start = span.end()
    parts.append(BARE_URL.sub(r"<\g<0>>", line[start:]))
    return "".join(parts)


def format_markdown(text: str, path: pathlib.Path) -> str:
    """Apply rumdl's fixes, one sentence per line among them, as the pre-commit hook does."""
    result = subprocess.run(
        [
            "rumdl",
            "fmt",
            "-",
            "--stdin-filename",
            str(path.relative_to(ROOT)),
            "--silent",
        ],
        input=text,
        capture_output=True,
        text=True,
        cwd=ROOT,
        check=False,
    )
    # rumdl exits 1 when unfixable issues remain; those the hook reports anyway
    if result.returncode not in (0, 1) or not result.stdout:
        sys.exit(f"error: rumdl failed on {path}:\n{result.stderr}")
    return result.stdout


def render_readme(readme: pathlib.Path, parameters: str) -> str:
    """The README with the parameter list between the markers replaced."""
    text = readme.read_text()
    begin, end = text.find(BEGIN_MARKER), text.find(END_MARKER)
    if begin < 0 or end < begin:
        sys.exit(f"error: {readme} lacks the config-docs markers")
    text = text[: begin + len(BEGIN_MARKER)] + "\n\n" + parameters + "\n\n" + text[end:]
    return format_markdown(text, readme)


def expected_files(member: pathlib.Path, config) -> dict[pathlib.Path, str]:
    """Each generated file of the member and the content it should have."""
    schema = render_schema(config)
    files = {
        member / SCHEMA_FILE: schema,
        member / EXAMPLE_FILE: render_example(config),
    }
    readme = member / README_FILE
    files[readme] = render_readme(readme, render_parameters(schema))
    if (member / OPENAPI_FILE).is_file():
        files[member / OPENAPI_FILE] = render_openapi(openapi_app(member, config))
    return files


def main() -> int:
    """Update or check the configuration docs."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail on stale files")
    parser.add_argument("paths", nargs="*", help="members or files, default all")
    args = parser.parse_args()
    # importing the services warns about their own deprecated calls, which their
    # tests report; here it would only bury the result
    warnings.simplefilter("ignore")

    stale = []
    unmasked: list[str] = []
    for member in members(args.paths):
        config = load_config(member)
        secret_fields = SECRET_FIELDS.get(member.name, set())
        unmasked.extend(
            f"  {member.relative_to(ROOT)}: {path}"
            for path in unmasked_secrets(type(config), secret_fields)
        )
        for path, content in expected_files(member, config).items():
            current = path.read_text() if path.is_file() else ""
            if current == content:
                continue
            stale.append(path.relative_to(ROOT))
            if args.check:
                sys.stdout.writelines(
                    difflib.unified_diff(
                        current.splitlines(keepends=True),
                        content.splitlines(keepends=True),
                        fromfile=f"{path.relative_to(ROOT)} (committed)",
                        tofile=f"{path.relative_to(ROOT)} (generated)",
                    )
                )
            else:
                path.write_text(content)

    if unmasked:
        listing = "\n".join(unmasked)
        print(
            "Secret config values not typed as a pydantic Secret, so the startup log"
            f" shows them in clear text:\n{listing}\nType them as SecretStr, or add"
            " the name to NOT_SECRET in scripts/service_docs.py with the reason.",
            file=sys.stderr,
        )
    failed = bool(unmasked)
    if stale:
        listing = "\n".join(f"  {path}" for path in stale)
        if args.check:
            print(
                f"\nOut of date; run `just service-docs`:\n{listing}", file=sys.stderr
            )
            failed = True
        else:
            print(f"Updated:\n{listing}")
    return int(failed)


if __name__ == "__main__":
    sys.exit(main())
